"""Generate the firmware constants from the single engineering parameter source."""
from pathlib import Path
import argparse
import hashlib
import json

ROOT = Path(__file__).resolve().parents[1]
FIELDS = {
    "Q_MIN": ("joint", "soft_min_rad"), "Q_MAX": ("joint", "soft_max_rad"),
    "Q_HARD_MIN": ("joint", "hard_min_rad"), "Q_HARD_MAX": ("joint", "hard_max_rad"),
    "V_MAX": ("joint", "max_velocity_rad_s"), "A_MAX": ("joint", "max_acceleration_rad_s2"),
    "T_CONT": ("joint", "continuous_torque_nm"), "T_PEAK": ("joint", "peak_torque_nm"),
    "PEAK_SECONDS": ("joint", "peak_duration_s"), "TORQUE_PER_AMP": ("drive", "joint_torque_per_amp_nm"),
    "I_CONT": ("drive", "continuous_current_a"), "I_PEAK": ("drive", "peak_current_a"),
    "I_TRIP": ("drive", "trip_current_a"), "VBUS_MIN": ("drive", "supply_min_v"),
    "VBUS_MAX": ("drive", "supply_max_v"), "KP": ("control", "kp_nm_rad"),
    "KD": ("control", "kd_nm_s_rad"), "CURRENT_KP": ("control", "current_kp_duty_a"),
    "CURRENT_KI": ("control", "current_ki_duty_as"), "TEMP_TRIP": ("control", "temperature_trip_c"),
    "TEMP_RESET": ("control", "temperature_reset_c"), "HB_SECONDS": ("control", "heartbeat_timeout_s"),
    "MODEL_INERTIA": ("model", "inertia_kg_m2"), "MODEL_DAMPING": ("model", "damping_nm_s_rad"),
    "MODEL_GRAVITY": ("model", "gravity_coefficient_nm"), "GEAR_RATIO": ("drive", "gear_ratio"),
    "BELT_RATIO": ("drive", "belt_ratio"), "TOTAL_RATIO": ("drive", "total_ratio"),
}


def render():
    raw = (ROOT / "config/robot.json").read_bytes()
    data = json.loads(raw)
    assert abs(data["drive"]["gear_ratio"] * data["drive"]["belt_ratio"] - data["drive"]["total_ratio"]) < 1e-8
    assert data["joint"]["hard_min_rad"] < data["joint"]["soft_min_rad"] < data["joint"]["soft_max_rad"] < data["joint"]["hard_max_rad"]
    lines = ["/* Generated by tools/generate_config.py; do not edit. SPDX-License-Identifier: Apache-2.0 */", "#ifndef OEE_CONFIG_H", "#define OEE_CONFIG_H", '#define CFG_SOURCE_SHA256 "' + hashlib.sha256(raw).hexdigest() + '"']
    for name, (section, key) in FIELDS.items():
        number = f"{float(data[section][key]):.12g}"
        if "." not in number and "e" not in number.lower():
            number += ".0"
        lines.append(f"#define CFG_{name} {number}f")
    lines += ["#define CFG_TICK_MS 1u", "#define CFG_STATUS_MS 50u", "#endif", ""]
    return "\n".join(lines)


if __name__ == "__main__":
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    target = ROOT / "firmware/include/config_generated.h"
    content = render()
    if args.check:
        if not target.exists() or target.read_text(encoding="utf-8") != content:
            raise SystemExit("generated firmware configuration is stale")
        print("generated configuration: consistent")
    else:
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_text(content, encoding="utf-8")
        print("generated firmware/include/config_generated.h")
